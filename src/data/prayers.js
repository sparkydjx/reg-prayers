/**
 * @param {string} setId
 */
function buildRosary(setId) {
  const set = mysterySets.find((item) => item.id === setId)
  if (!set) return undefined

  /** @type {Devotion['steps']} */
  const steps = [
    { type: 'section', title: 'Opening', latinTitle: 'Initium' },
    { type: 'prayer', id: 'sign-of-the-cross' },
    { type: 'prayer', id: 'apostles-creed' },
    { type: 'prayer', id: 'our-father' },
    { type: 'prayer', id: 'hail-mary' },
    {
      type: 'note',
      text: 'Say this same Hail Mary three times.',
      latinText: 'Haec eadem Ave Maria ter dicitur.'
    },
    { type: 'prayer', id: 'glory-be' },
    { type: 'prayer', id: 'fatima-decade-prayer' }
  ]

  set.mysteryIds.forEach((mysteryId, index) => {
    steps.push({
      type: 'section',
      title: `Decade ${index + 1}`,
      latinTitle: `Decas ${index + 1}`
    })
    steps.push({ type: 'prayer', id: mysteryId })
    steps.push(...decadePrayers)
  })

  steps.push(
    { type: 'section', title: 'Closing', latinTitle: 'Conclusio' },
    { type: 'prayer', id: 'hail-holy-queen' },
    { type: 'prayer', id: 'final-rosary-prayer' },
    { type: 'prayer', id: 'sign-of-the-cross' }
  )

  return {
    id: `rosary-${set.id}`,
    category: 'rosary-chaplet',
    title: 'Holy Rosary',
    setBase: 'rosary',
    sets: mysterySets,
    activeSet: set,
    steps
  }
}

